const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("alloy_lang") || "tr");
  const change = useCallback((l) => { localStorage.setItem("alloy_lang", l); setLang(l); }, []);
  const t = useCallback((key) => (STR[lang] && STR[lang][key]) || STR.en[key] || key, [lang]);
  return <I18nContext.Provider value={{ lang, setLang: change, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
